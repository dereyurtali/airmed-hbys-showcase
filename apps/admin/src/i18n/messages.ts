const messages: Record<Locale, MessageTree> = { tr, en };

function lookup(tree: MessageTree, key: string): string | undefined {
  const parts = key.split('.');
  let node: string | MessageTree | undefined = tree;
  for (const part of parts) {
    if (typeof node !== 'object' || node === null) return undefined;
    node = node[part];
  }
  return typeof node === 'string' ? node : undefined;
}

function interpolate(raw: string, vars?: Record<string, string | number>): string {
  if (!vars) return raw;
  return raw.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{{${name}}}`,
  );
}

/** TR kanonik; EN'de eksik anahtar TR'ye, o da yoksa key'in kendisine düşer. */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = lookup(messages[locale], key) ?? lookup(messages[DEFAULT_LOCALE], key) ?? key;
  return interpolate(raw, vars);
}
